def list_templates():
    return sorted(
        p.name for p in TEMPLATES_DIR.glob('*.docx')
        if not p.name.startswith('~$')
    )


def build_context_for_template(template_name):
    """Контекст только с переменными, которые есть в шаблоне."""
    path = TEMPLATES_DIR / template_name
    variables = list_template_variables(path)
    return {var: BASE_CONTEXT.get(var, f'тест-{var}') for var in variables}


def expected_phrases(template_name, context):
    """Фразы, которые должны встретиться в тексте после рендера."""
    phrases = list(TEMPLATE_EXTRA_PHRASES.get(template_name, []))
    # Универсальные маркеры из контекста
    for key in ('номер_договора', 'фио_клиента', 'фио_эксперта', 'номер_дела', 'исх_номер'):
        val = context.get(key)
        if val and str(val) not in phrases:
            phrases.append(str(val))
    return phrases
