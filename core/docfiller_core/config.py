class _AttrDict(dict):
    """Словарь, доступ к ключам которого работает и через точку.

    В шаблонах docxtpl/Jinja2 это позволяет писать
        {{ настройки.организация.инн }}
    как короткую форму вместо
        {{ настройки['организация']['инн'] }}.
    """
    def __getattr__(self, name):
        try:
            value = self[name]
        except KeyError:
            return ''
        return value

    def __setattr__(self, name, value):
        self[name] = value


def _to_attrdict(obj):
    """Рекурсивно превратить вложенные словари в _AttrDict."""
    if isinstance(obj, dict):
        return _AttrDict({k: _to_attrdict(v) for k, v in obj.items()})
    if isinstance(obj, list):
        return [_to_attrdict(v) for v in obj]
    return obj


def _deep_merge(base, override):
    """Слить два словаря: значения из override перекрывают base, dict — рекурсивно."""
    result = dict(base)
    for key, value in (override or {}).items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = _deep_merge(result[key], value)
        else:
            result[key] = value
    return result


def _active_config_path():
    """Актуальный путь к настройкам (с учётом monkeypatch CONFIG_PATH)."""
    return CONFIG_PATH if CONFIG_PATH is not None else paths.config_path()


def load_settings():
    """Прочитать «настройки.yaml» и вернуть объект для использования в шаблонах.

    Если файл отсутствует или повреждён — вернуть структуру по умолчанию.
    Любые ошибки чтения проглатываются: пользователь не должен оставаться
    без возможности сгенерировать документ из-за опечатки в YAML.
    """
    path = _active_config_path()
    if not path.exists():
        return _to_attrdict(DEFAULTS)
    try:
        with path.open(encoding='utf-8') as f:
            data = yaml.safe_load(f) or {}
        return settings_from_dict(data)
    except Exception:
        # Не прокидываем исключение наверх — пусть документ сгенерируется
        # хотя бы с дефолтами. GUI отдельно покажет предупреждение.
        return _to_attrdict(DEFAULTS)


def settings_from_dict(data):
    """Словарь реквизитов организации (как JSONB) → объект «настройки» для шаблонов."""
    merged = _deep_merge(DEFAULTS, data or {})
    return _to_attrdict(merged)


def load_settings_with_error():
    """То же, что load_settings, но возвращает (настройки, текст_ошибки).

    Используется в GUI, чтобы показать пользователю предупреждение
    о повреждённом YAML, не блокируя при этом работу.
    """
    path = _active_config_path()
    if not path.exists():
        return _to_attrdict(DEFAULTS), ''
    try:
        with path.open(encoding='utf-8') as f:
            data = yaml.safe_load(f) or {}
        merged = _deep_merge(DEFAULTS, data)
        return _to_attrdict(merged), ''
    except Exception as e:
        return _to_attrdict(DEFAULTS), str(e)


def ensure_config_exists():
    """Создать файл «настройки.yaml» с образцом, если его ещё нет.

    Вызывается при старте приложения. Не перезаписывает существующий файл.
    """
    path = _active_config_path()
    if path.exists():
        return False
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(_SAMPLE_YAML, encoding='utf-8')
        return True
    except Exception:
        return False


def get_config_path():
    """Путь к файлу настроек."""
    return _active_config_path()


def read_settings_yaml():
    """Прочитать сырой текст «настройки.yaml» для редактора."""
    path = _active_config_path()
    if not path.exists():
        return _SAMPLE_YAML
    try:
        return path.read_text(encoding='utf-8')
    except Exception:
        return _SAMPLE_YAML


def load_settings_dict():
    """Словарь настроек (merged с DEFAULTS) для форм UI."""
    settings, _err = load_settings_with_error()
    return _from_attrdict(settings)


def _from_attrdict(obj):
    """AttrDict / вложенные объекты → обычный dict."""
    if isinstance(obj, dict):
        return {k: _from_attrdict(v) for k, v in obj.items()}
    if hasattr(obj, 'items') and not isinstance(obj, (str, bytes)):
        try:
            return {k: _from_attrdict(v) for k, v in obj.items()}
        except Exception:
            return obj
    return obj


def save_settings_dict(data):
    """Сохранить словарь настроек в YAML. Возвращает '' или текст ошибки."""
    if not isinstance(data, dict):
        return 'Корень настроек должен быть словарём.'
    try:
        merged = _deep_merge(DEFAULTS, data)
        # Числа в прайсе/константах
        for section in ('прайс', 'константы'):
            block = merged.get(section) or {}
            for key, val in list(block.items()):
                if val in (None, ''):
                    continue
                try:
                    if isinstance(val, str) and '.' in val:
                        block[key] = float(val.replace(',', '.').replace(' ', ''))
                    else:
                        block[key] = int(str(val).replace(' ', ''))
                except (TypeError, ValueError):
                    pass
            merged[section] = block

        text = yaml.safe_dump(
            merged,
            allow_unicode=True,
            default_flow_style=False,
            sort_keys=False,
            width=1000,
        )
        path = _active_config_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
        return ''
    except Exception as e:
        return str(e)


def save_settings_yaml(text):
    """Сохранить YAML после проверки синтаксиса. Возвращает текст ошибки или ''."""
    try:
        parsed = yaml.safe_load(text)
        if parsed is not None and not isinstance(parsed, dict):
            return 'Корень файла должен быть словарём (блоки с отступами).'
        path = _active_config_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
        return ''
    except Exception as e:
        return str(e)
